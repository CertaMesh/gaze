#!/usr/bin/env python3
"""Regenerate the English name-word asset for caller-known single-name records.

A declared single-token name that is also an ordinary English word (`Summer`,
`Dawn`, `Will`) needs corroboration before Gaze protects it, in every letter
case. This script derives that set from two external sources with fixed,
source-defined cut-offs, never from benchmark text:

* Names: US Social Security Administration national baby-name data
  (public domain, a US government work), 1880 onward. A name qualifies when it
  ranks in the SSA's published top 1,000 for either sex in any year.
* Words: the default en_US Hunspell dictionary from SCOWL (size 60). A stem
  counts as an ordinary word when it starts with a lowercase letter; Hunspell
  capitalizes proper nouns.

The asset is the case-folded intersection. Both downloads are pinned by
SHA-256; a changed source fails instead of silently changing the list.

Usage, from the repository root:

    python3 -I scripts/fetch/build_record_common_name_words.py [--check] \\
        [--ssa-zip names.zip] [--scowl-zip hunspell-en_US.zip]
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import io
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSET = ROOT / "crates/gaze-recognizers/assets/record-common-name-words-en-v1.txt"

# The SSA blocks scripted downloads; this Wayback snapshot is the same file.
SSA_URL = "https://web.archive.org/web/20261112035540id_/https://www.ssa.gov/oact/babynames/names.zip"
SSA_SHA256 = "cd78e975ed7bb358e018dd62fbe14ced89295e9581c49172ca4eedcb011b3724"
SCOWL_URL = "https://github.com/en-wl/wordlist/releases/download/rel-2026.02.25/hunspell-en_US-2026.02.25.zip"
SCOWL_SHA256 = "ac8e73310e951d88c52c2cf2ba54ceaca34f8486a81630ac8a75dc5f931179f9"
TOP_RANK = 1000

HEADER = f"""\
# Generated by scripts/fetch/build_record_common_name_words.py; do not edit.
# English given names that are also ordinary words, case-folded.
# Names: SSA national baby names, any year's top {TOP_RANK} for either sex.
#   {SSA_URL}
#   sha256 {SSA_SHA256}; public domain (US government work).
# Words: lowercase stems of SCOWL's default en_US Hunspell dictionary (size 60).
#   {SCOWL_URL}
#   sha256 {SCOWL_SHA256}
# SCOWL notice: Copyright 2000-2026 by Kevin Atkinson. Permission to use, copy,
# modify, distribute, and sell any part of SCOWLv2, or word lists created from
# it, is hereby granted without fee, provided that the above copyright notice
# appears in all copies and that both the above copyright notice and this
# notice appear in supporting documentation. Kevin Atkinson makes no
# representations about the suitability of this database for any purpose. It
# is provided "as is" without express or implied warranty.
"""


def fetch(url: str, sha256: str, local: Path | None) -> bytes:
    if local is not None:
        data = local.read_bytes()
    else:
        # The Wayback Machine refuses urllib; curl follows its redirect.
        data = subprocess.run(["curl", "-fsSL", "--retry", "3", url], check=True, capture_output=True).stdout
    if hashlib.sha256(data).hexdigest() != sha256:
        raise SystemExit(f"source hash mismatch for {url}")
    return data


def ssa_names(archive: bytes) -> set[str]:
    names: set[str] = set()
    with zipfile.ZipFile(io.BytesIO(archive)) as zipped:
        for member in sorted(zipped.namelist()):
            if not (member.startswith("yob") and member.endswith(".txt")):
                continue
            by_sex: dict[str, list[tuple[int, str]]] = collections.defaultdict(list)
            for line in zipped.read(member).decode("ascii").splitlines():
                name, sex, count = line.split(",")
                by_sex[sex].append((-int(count), name))
            for ranked in by_sex.values():
                names.update(name.casefold() for _, name in sorted(ranked)[:TOP_RANK])
    return names


def dictionary_words(archive: bytes) -> set[str]:
    with zipfile.ZipFile(io.BytesIO(archive)) as zipped:
        lines = zipped.read("en_US.dic").decode("utf-8").splitlines()[1:]
    stems = (line.split("/", 1)[0].strip() for line in lines)
    return {stem.casefold() for stem in stems if stem and stem[0].islower() and stem.isalpha()}


def render(ssa_zip: Path | None, scowl_zip: Path | None) -> str:
    names = ssa_names(fetch(SSA_URL, SSA_SHA256, ssa_zip))
    words = sorted(names & dictionary_words(fetch(SCOWL_URL, SCOWL_SHA256, scowl_zip)))
    return HEADER + "".join(f"{word}\n" for word in words)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed asset differs")
    parser.add_argument("--ssa-zip", type=Path, help="local copy of the pinned SSA archive")
    parser.add_argument("--scowl-zip", type=Path, help="local copy of the pinned Hunspell archive")
    args = parser.parse_args()
    rendered = render(args.ssa_zip, args.scowl_zip)
    if args.check:
        if ASSET.read_text(encoding="utf-8") != rendered:
            print(f"{ASSET.relative_to(ROOT)} is stale", file=sys.stderr)
            return 1
        return 0
    ASSET.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
