#!/usr/bin/env python3
"""Measure adopter-facing latency of the `gaze setup` policy on a quiet host.

Three measurements over the same stratified benchmark documents (seed 20260710;
the first sampled document is the warm-up and is never scored):

  pipeline      warm per-document `clean_ms` from the benchmark runner
                (`clean_for_bench`, the production pipeline) for the exact
                `gaze setup` policy without and with Nym, and for rules plus NER
                (`pass2-ner`) on this build and on a checkout at tag v0.14.0, so
                a code slowdown is separable from the setup policy's extra packs
                and locales. Also the cold first document and peak RSS.
  cli           one `gaze clean --policy` process per document against one
                `gaze daemon --policy` process with one JSONL request per
                document (the first request is cold), without and with Nym.
                Wall clock includes process start and model load for one-shot.
  conversation  one `gaze daemon` session, 10 turns; turn k re-sends turns
                1..k joined, as an agent loop does.
  proxy         one `gaze proxy serve --policy` process in front of a local
                echo upstream (no network, no provider time): one OpenAI chat
                request per document, wall clock per request. The upstream
                returns the forwarded text, so every accepted response must
                restore to the document exactly; a refusal (422) is counted,
                anything else fails the run.

The policies are generated by the `gaze` binary under test with
`gaze setup --non-interactive --policy-out <tmp> --force` (and
`--safety-net none` for the no-Nym policy), never hand-written: a hand-written
`[session] scope = "ephemeral"` policy makes one-shot `gaze clean` fail.

Timing is only a claim on a quiet host: at the start the 1-minute load average
must be below 2 and no foreign cargo, rustc, benchmark or OPF process may run;
at the end no foreign process may have appeared (the measured workload's own
load is expected). Both probes are recorded either way, and a run that fails
the gate says `timing invalid`. `--smoke` measures 3 documents, skips the gate
and is never a timing claim. Document text stays in memory.

Usage (from the repository root; needs `gaze setup` models and the pinned
dataset under target/bench-data/dataiku-en-de/):

    uv run --project scripts/bench python scripts/bench/cli-latency.py \\
        --baseline-root <checkout at the previous release> \\
        --baseline-version v0.15.0 --out latency.json
"""

